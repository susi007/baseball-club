-- =========================================================================
-- 5. 各テーブルの RLS ポリシー設定
-- =========================================================================

-- ─── income テーブル ───
DROP POLICY IF EXISTS income_select_authenticated ON public.income;
CREATE POLICY income_select_authenticated ON public.income
    FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS income_insert_admin ON public.income;
CREATE POLICY income_insert_admin ON public.income
    FOR INSERT TO authenticated WITH CHECK (public.is_club_admin());

DROP POLICY IF EXISTS income_update_admin ON public.income;
CREATE POLICY income_update_admin ON public.income
    FOR UPDATE TO authenticated USING (public.is_club_admin()) WITH CHECK (public.is_club_admin());

DROP POLICY IF EXISTS income_delete_admin ON public.income;
CREATE POLICY income_delete_admin ON public.income
    FOR DELETE TO authenticated USING (public.is_club_admin());

