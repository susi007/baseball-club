CREATE OR REPLACE FUNCTION public.save_equipment_assignments(
    p_equipment_id bigint,
    p_changed_on date,
    p_assignments jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_equipment public.equipment_items%ROWTYPE;
    v_before jsonb;
    v_after jsonb;
    v_nickname varchar(30);
    v_purchased_quantity bigint;
    v_assigned_quantity bigint;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'ログインが必要です。';
    END IF;

    SELECT *
    INTO v_equipment
    FROM public.equipment_items
    WHERE id = p_equipment_id
      AND disposed_on IS NULL
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION '備品が見つからないか、既に廃棄されています。';
    END IF;

    IF p_changed_on IS NULL
       OR jsonb_typeof(p_assignments) IS DISTINCT FROM 'array'
       OR jsonb_array_length(p_assignments) = 0 THEN
        RAISE EXCEPTION '変更日と管理者・個数を入力してください。';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM jsonb_array_elements(p_assignments) AS entry(value)
        WHERE jsonb_typeof(entry.value) IS DISTINCT FROM 'object'
           OR NULLIF(btrim(entry.value ->> 'manager'), '') IS NULL
           OR jsonb_typeof(entry.value -> 'quantity') IS DISTINCT FROM 'number'
           OR (entry.value ->> 'quantity') !~ '^[1-9][0-9]*$'
           OR CASE
               WHEN (entry.value ->> 'quantity') ~ '^[1-9][0-9]*$'
               THEN (entry.value ->> 'quantity')::numeric > 2147483647
               ELSE false
           END
    ) THEN
        RAISE EXCEPTION '管理者と1以上の個数を正しく入力してください。';
    END IF;

    IF EXISTS (
        SELECT btrim(entry.value ->> 'manager')
        FROM jsonb_array_elements(p_assignments) AS entry(value)
        GROUP BY btrim(entry.value ->> 'manager')
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION '同じ管理者を複数行に登録できません。';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM jsonb_array_elements(p_assignments) AS entry(value)
        WHERE NOT EXISTS (
            SELECT 1
            FROM public.profiles AS profile
            WHERE profile.nickname = btrim(entry.value ->> 'manager')
        )
        AND NOT EXISTS (
            SELECT 1
            FROM public.equipment_assignments AS assignment
            WHERE assignment.equipment_id = p_equipment_id
              AND assignment.manager = btrim(entry.value ->> 'manager')
        )
    ) THEN
        RAISE EXCEPTION '管理者には登録済みのニックネームを指定してください。';
    END IF;

    SELECT COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'manager', assignment.manager,
                'quantity', assignment.quantity
            )
            ORDER BY assignment.manager
        ),
        '[]'::jsonb
    )
    INTO v_before
    FROM public.equipment_assignments AS assignment
    WHERE assignment.equipment_id = p_equipment_id;

    SELECT COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'manager', btrim(entry.value ->> 'manager'),
                'quantity', (entry.value ->> 'quantity')::integer
            )
            ORDER BY btrim(entry.value ->> 'manager')
        ),
        '[]'::jsonb
    )
    INTO v_after
    FROM jsonb_array_elements(p_assignments) AS entry(value);

    SELECT COALESCE(sum(inventory.quantity), 0)
    INTO v_purchased_quantity
    FROM public.inventory AS inventory
    WHERE inventory.name = v_equipment.name
      AND inventory.category <> 'グラウンド';

    SELECT COALESCE(sum((entry.value ->> 'quantity')::bigint), 0)
    INTO v_assigned_quantity
    FROM jsonb_array_elements(p_assignments) AS entry(value);

    IF v_assigned_quantity <> v_purchased_quantity THEN
        RAISE EXCEPTION
            '管理者ごとの個数合計（%個）を購入済み個数（%個）に合わせてください。',
            v_assigned_quantity,
            v_purchased_quantity;
    END IF;

    IF v_before IS DISTINCT FROM v_after
       OR v_equipment.changed_on IS DISTINCT FROM p_changed_on THEN
        SELECT nickname
        INTO v_nickname
        FROM public.profiles
        WHERE id = auth.uid();

        INSERT INTO public.equipment_history (
            equipment_id,
            changed_on,
            before_state,
            after_state,
            changed_by,
            changed_by_nickname
        )
        VALUES (
            p_equipment_id,
            p_changed_on,
            v_before,
            v_after,
            auth.uid(),
            COALESCE(v_nickname, '不明')
        );

        DELETE FROM public.equipment_assignments
        WHERE equipment_id = p_equipment_id;

        INSERT INTO public.equipment_assignments (
            equipment_id,
            manager,
            quantity
        )
        SELECT
            p_equipment_id,
            btrim(entry.value ->> 'manager'),
            (entry.value ->> 'quantity')::integer
        FROM jsonb_array_elements(p_assignments) AS entry(value);

        UPDATE public.equipment_items
        SET changed_on = p_changed_on
        WHERE id = p_equipment_id;
    END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.save_equipment_assignments(bigint, date, jsonb)
FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.save_equipment_assignments(bigint, date, jsonb)
TO authenticated;

CREATE OR REPLACE FUNCTION public.dispose_equipment(p_equipment_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_equipment public.equipment_items%ROWTYPE;
    v_before jsonb;
    v_nickname varchar(30);
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'ログインが必要です。';
    END IF;

    SELECT *
    INTO v_equipment
    FROM public.equipment_items
    WHERE id = p_equipment_id
      AND disposed_on IS NULL
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION '備品が見つからないか、既に廃棄されています。';
    END IF;

    SELECT COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'manager', assignment.manager,
                'quantity', assignment.quantity
            )
            ORDER BY assignment.manager
        ),
        '[]'::jsonb
    )
    INTO v_before
    FROM public.equipment_assignments AS assignment
    WHERE assignment.equipment_id = p_equipment_id;

    SELECT nickname
    INTO v_nickname
    FROM public.profiles
    WHERE id = auth.uid();

    INSERT INTO public.equipment_history (
        equipment_id,
        changed_on,
        before_state,
        after_state,
        changed_by,
        changed_by_nickname,
        change_type
    )
    VALUES (
        p_equipment_id,
        CURRENT_DATE,
        v_before,
        '[]'::jsonb,
        auth.uid(),
        COALESCE(v_nickname, '不明'),
        'disposal'
    );

    UPDATE public.equipment_items
    SET disposed_on = CURRENT_DATE,
        changed_on = CURRENT_DATE
    WHERE id = p_equipment_id;
END;
$$;

REVOKE ALL ON FUNCTION public.dispose_equipment(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.dispose_equipment(bigint) TO authenticated;

CREATE OR REPLACE FUNCTION public.add_purchased_equipment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_equipment_id bigint;
    v_before jsonb;
    v_after jsonb;
    v_nickname varchar(30);
BEGIN
    IF NEW.category = 'グラウンド' THEN
        RETURN NEW;
    END IF;

    INSERT INTO public.equipment_items AS current_equipment (
        name,
        category,
        changed_on
    )
    VALUES (NEW.name, NEW.category, NEW.date)
    ON CONFLICT (name) DO UPDATE
        SET category = EXCLUDED.category,
            changed_on = GREATEST(current_equipment.changed_on, EXCLUDED.changed_on),
            disposed_on = NULL
    RETURNING id INTO v_equipment_id;

    SELECT COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'manager', assignment.manager,
                'quantity', assignment.quantity
            )
            ORDER BY assignment.manager
        ),
        '[]'::jsonb
    )
    INTO v_before
    FROM public.equipment_assignments AS assignment
    WHERE assignment.equipment_id = v_equipment_id;

    INSERT INTO public.equipment_assignments AS current_assignment (
        equipment_id,
        manager,
        quantity
    )
    VALUES (v_equipment_id, NEW.owner, NEW.quantity)
    ON CONFLICT (equipment_id, manager) DO UPDATE
        SET quantity = current_assignment.quantity + EXCLUDED.quantity;

    SELECT COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'manager', assignment.manager,
                'quantity', assignment.quantity
            )
            ORDER BY assignment.manager
        ),
        '[]'::jsonb
    )
    INTO v_after
    FROM public.equipment_assignments AS assignment
    WHERE assignment.equipment_id = v_equipment_id;

    SELECT nickname
    INTO v_nickname
    FROM public.profiles
    WHERE id = auth.uid();

    INSERT INTO public.equipment_history (
        equipment_id,
        changed_on,
        before_state,
        after_state,
        changed_by,
        changed_by_nickname
    )
    VALUES (
        v_equipment_id,
        NEW.date,
        v_before,
        v_after,
        auth.uid(),
        COALESCE(v_nickname, NEW.owner)
    );

    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.add_purchased_equipment() FROM PUBLIC;

DROP TRIGGER IF EXISTS inventory_adds_equipment
    ON public.inventory;
CREATE TRIGGER inventory_adds_equipment
    AFTER INSERT ON public.inventory
    FOR EACH ROW EXECUTE FUNCTION public.add_purchased_equipment();
