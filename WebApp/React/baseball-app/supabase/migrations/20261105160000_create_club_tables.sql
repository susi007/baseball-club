-- =========================================================================
-- 1. テーブルの作成 (Income, Inventory, Club Admins)
-- =========================================================================

CREATE TABLE IF NOT EXISTS public.income (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    name varchar(100) NOT NULL,
    amount integer NOT NULL CHECK (amount > 0),
    people integer NOT NULL DEFAULT 1 CHECK (people > 0)
);

CREATE TABLE IF NOT EXISTS public.inventory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    name varchar(100) NOT NULL,
    category varchar(50) NOT NULL,
    amount integer NOT NULL CHECK (amount >= 0),
    quantity integer NOT NULL CHECK (quantity > 0),
    owner varchar(100) NOT NULL
);

-- 【変更点】管理者マスタテーブルを新規追加
CREATE TABLE IF NOT EXISTS public.club_admins (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE CHECK (email = lower(email)),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =========================================================================
-- 2. セキュリティ設定の初期化 (Row Level Security & 初期権限の剥奪)
-- =========================================================================

ALTER TABLE public.income ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.club_admins ENABLE ROW LEVEL SECURITY; -- 【変更点】RLSを有効化

REVOKE ALL ON TABLE public.income, public.inventory, public.club_admins FROM anon, authenticated;

-- 一般認証ユーザー（authenticated）への基本権限付与
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.income, public.inventory TO authenticated;
-- 【変更点】一般ユーザーから club_admins への SELECT 権限は付与しない（完全に隠すため）

-- 【補足】環境によってINSERTエラーが出るのを防ぐシーケンス権限
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- =========================================================================
-- 3. 管理者判定関数の定義 (SECURITY DEFINER で安全にテーブルを参照)
-- =========================================================================

-- 【変更点】テーブル参照方式に切り替え ＋ SECURITY DEFINER を追加
CREATE OR REPLACE FUNCTION public.is_club_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER 
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 
        FROM public.club_admins 
        WHERE email = lower(auth.jwt() ->> 'email')
    );
$$;

REVOKE ALL ON FUNCTION public.is_club_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_club_admin() TO authenticated;

