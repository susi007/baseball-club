CREATE TABLE IF NOT EXISTS public.equipment_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    category varchar(50) NOT NULL DEFAULT 'その他',
    changed_on date NOT NULL,
    disposed_on date
);

ALTER TABLE public.equipment_items
    ADD COLUMN IF NOT EXISTS category varchar(50) NOT NULL DEFAULT 'その他';
ALTER TABLE public.equipment_items
    ADD COLUMN IF NOT EXISTS disposed_on date;

UPDATE public.equipment_items AS equipment
SET category = inventory.category
FROM (
    SELECT DISTINCT ON (name) name, category
    FROM public.inventory
    ORDER BY name, date DESC, id DESC
) AS inventory
WHERE inventory.name = equipment.name;

CREATE TABLE IF NOT EXISTS public.equipment_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id bigint NOT NULL
        REFERENCES public.equipment_items(id) ON DELETE CASCADE,
    manager varchar(100) NOT NULL
        CHECK (char_length(btrim(manager)) > 0),
    quantity integer NOT NULL CHECK (quantity > 0),
    UNIQUE (equipment_id, manager)
);

CREATE TABLE IF NOT EXISTS public.equipment_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id bigint NOT NULL
        REFERENCES public.equipment_items(id) ON DELETE CASCADE,
    changed_on date NOT NULL,
    before_state jsonb NOT NULL,
    after_state jsonb NOT NULL,
    changed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    changed_by_nickname varchar(30) NOT NULL,
    change_type varchar(20) NOT NULL DEFAULT 'assignment_change'
        CHECK (change_type IN ('assignment_change', 'disposal')),
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE public.equipment_history
    ADD COLUMN IF NOT EXISTS change_type varchar(20) NOT NULL
    DEFAULT 'assignment_change';

CREATE INDEX IF NOT EXISTS equipment_history_item_created_idx
    ON public.equipment_history (equipment_id, created_at DESC);

INSERT INTO public.equipment_items (name, category, changed_on)
SELECT latest.name, latest.category, dates.changed_on
FROM (
    SELECT DISTINCT ON (name) name, category
    FROM public.inventory
    ORDER BY name, date DESC, id DESC
) AS latest
JOIN (
    SELECT name, max(date) AS changed_on
    FROM public.inventory
    GROUP BY name
) AS dates ON dates.name = latest.name
WHERE latest.category <> 'グラウンド'
ON CONFLICT (name) DO NOTHING;

INSERT INTO public.equipment_assignments (equipment_id, manager, quantity)
SELECT equipment.id, inventory.owner, sum(inventory.quantity)::integer
FROM public.inventory AS inventory
JOIN public.equipment_items AS equipment ON equipment.name = inventory.name
WHERE inventory.category <> 'グラウンド'
GROUP BY equipment.id, inventory.owner
ON CONFLICT (equipment_id, manager) DO NOTHING;

INSERT INTO public.equipment_history (
    equipment_id,
    changed_on,
    before_state,
    after_state,
    changed_by_nickname
)
SELECT
    equipment.id,
    equipment.changed_on,
    '[]'::jsonb,
    COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'manager', assignment.manager,
                'quantity', assignment.quantity
            )
            ORDER BY assignment.manager
        ) FILTER (WHERE assignment.id IS NOT NULL),
        '[]'::jsonb
    ),
    '初期登録'
FROM public.equipment_items AS equipment
LEFT JOIN public.equipment_assignments AS assignment
    ON assignment.equipment_id = equipment.id
WHERE NOT EXISTS (
    SELECT 1
    FROM public.equipment_history AS history
    WHERE history.equipment_id = equipment.id
      AND history.changed_by_nickname = '初期登録'
)
GROUP BY equipment.id, equipment.changed_on
ON CONFLICT DO NOTHING;

ALTER TABLE public.equipment_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment_history ENABLE ROW LEVEL SECURITY;

